from __future__ import annotations

import hashlib


CALIBRATION_NAME_MAX_LENGTH = 128


def compact_generated_calibration_name(
    full_name: str,
    *,
    semantic_suffix: str | None = None,
    max_length: int = CALIBRATION_NAME_MAX_LENGTH,
) -> str:
    """Return a deterministic DB-safe calibration name.

    Generated calibration names are part of the scientific provenance, but the
    database intentionally limits ``calibration_versions.name`` to 128
    characters.  Short names are kept byte-for-byte unchanged.  Only names
    exceeding the limit are compacted, retaining a caller-supplied semantic
    suffix and inserting a stable hash of the *unabridged* name.

    This function is intended for names generated by Grandgousier.  Explicit
    user-provided names should normally be validated rather than silently
    rewritten.
    """

    name = str(full_name)
    if max_length < 16:
        raise ValueError("max_length must be at least 16 characters")
    if len(name) <= max_length:
        return name

    suffix = str(semantic_suffix or "")
    if suffix and not suffix.startswith("_"):
        suffix = f"_{suffix}"

    digest = hashlib.sha256(name.encode("utf-8")).hexdigest()[:10]
    hash_token = f"_h{digest}"
    tail = f"{hash_token}{suffix}"
    if len(tail) >= max_length:
        # A semantic suffix should always be short, but keep the failure mode
        # deterministic instead of returning another overlong name.
        suffix_budget = max(0, max_length - len(hash_token) - 1)
        suffix = suffix[-suffix_budget:] if suffix_budget else ""
        tail = f"{hash_token}{suffix}"

    prefix_budget = max_length - len(tail)
    prefix = name[:prefix_budget].rstrip("_")
    if not prefix:
        prefix = "calibration"[:prefix_budget]
    compacted = f"{prefix}{tail}"
    if len(compacted) > max_length:  # pragma: no cover - defensive invariant
        compacted = compacted[:max_length]
    return compacted


def candidate_excluded_calibration_name(
    base_ensemble_name: str,
    *,
    iteration: int,
) -> str:
    """Build a readable, deterministic candidate-exclusion calibration name."""

    if iteration < 2:
        raise ValueError("candidate-excluded ensemble iteration must be >= 2")

    stem = str(base_ensemble_name)
    if stem.endswith("_v1"):
        stem = stem[:-3]

    historical_suffix = (
        "_candidate_excluded_v1"
        if iteration == 2
        else f"_candidate_excluded_iter{iteration}_v1"
    )
    historical_name = f"{stem}{historical_suffix}"
    if len(historical_name) <= CALIBRATION_NAME_MAX_LENGTH:
        return historical_name

    compact_suffix = "_candx_v1" if iteration == 2 else f"_candx_iter{iteration}_v1"
    compact_name = f"{stem}{compact_suffix}"
    return compact_generated_calibration_name(
        compact_name,
        semantic_suffix=compact_suffix,
    )
